#' Build the `meta_data` documentation sheet from the schema.
#'
#' Emits the control-scalar rows, the fleet_control header + column rows, the
#' data-sheet header rows, the bioenergetics-scalar rows, and the tail sheet
#' headers + NOTE footer -- reproducing the layout of the bundled
#' `meta_data_names.xlsx`.
#'
#' @return A data.frame with columns `Sheet name`, `Column/row name`,
#'   `Description`.
#' @keywords internal
#' @noRd
.rce_build_meta_data_df <- function() {
  add <- function(acc, sheet, col, desc) {
    rbind(acc, data.frame(`Sheet name` = sheet, `Column/row name` = col,
                          Description = desc, check.names = FALSE,
                          stringsAsFactors = FALSE))
  }
  out <- data.frame(`Sheet name` = character(0), `Column/row name` = character(0),
                    Description = character(0), check.names = FALSE,
                    stringsAsFactors = FALSE)

  # Control scalars (Sheet name "Control")
  for (r in .rce_schema_rows("control"))
    if (isTRUE(r$meta)) out <- add(out, "Control", r$name, r$doc)

  # fleet_control header + columns
  out <- add(out, "fleet_control", NA_character_, .RCE_META_SHEET_HEADERS[[1]][2])
  for (r in .rce_schema_rows("fleet_control"))
    if (isTRUE(r$meta)) out <- add(out, "fleet_control", r$name, r$doc)

  # Data-sheet headers (index_data .. M1_base)
  for (h in .RCE_META_SHEET_HEADERS[-1]) out <- add(out, h[1], NA_character_, h[2])

  # bioenergetics scalars
  for (r in .rce_schema_rows("bioenergetics_control"))
    if (isTRUE(r$meta)) out <- add(out, "bioenergetics_control", r$name, r$doc)

  # Tail sheet headers
  for (h in .RCE_META_SHEET_HEADERS_TAIL) out <- add(out, h[1], NA_character_, h[2])

  # NOTE footer (carried in the Sheet name column, as in the bundled file)
  for (n in .RCE_META_NOTES) out <- add(out, n, NA_character_, NA_character_)

  out
}
