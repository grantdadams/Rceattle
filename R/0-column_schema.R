#'
#' Reproduces `switch_check()`'s local `set_default(val, default, msg)`: when
#' `val` is NULL, emit the schema's `default_msg` (gated by `default_msg_when`)
#' and return the schema `default`; otherwise return `val` unchanged. Sourcing
#' the value and message from the schema is what removes the hand-copied
#' defaults from `switch_check()`.
#'
#' @param val The current column value (NULL if the column is absent).
#' @param col Canonical column name (schema key).
#' @param schema A prefetched `.rce_column_schema()` (avoids rebuilding it per
#'   call).
#' @param np_hake Value of the non-parametric/Hake/LogisticPM predicate, for
#'   columns whose message only fires when such a fleet is present
#'   (`default_msg_when == "np_hake"`).
#' @keywords internal
#' @noRd
.rce_apply_default <- function(val, col, schema = .rce_column_schema(),
                               np_hake = FALSE, conditions = list()) {
  if (!is.null(val)) return(val)
  row <- schema[[col]]
  if (is.null(row) || !isTRUE(row$has_default))
    stop("Internal: no schema default for column '", col, "'")
  msg  <- row$default_msg
  # A gated default message fires only when its condition holds -- so we don't
  # nag about an optional input the current model configuration never uses (e.g.
  # a CAAL distribution for a model with no CAAL data). The gate is named in the
  # schema's `default_msg_when`; `np_hake` is the legacy first-class gate, every
  # other named gate is supplied in `conditions` (a named logical list computed by
  # switch_check()). An ungated message (no `default_msg_when`) always fires.
  gate <- row$default_msg_when
  if (!is.null(gate) && nzchar(gate)) {
    on <- if (identical(gate, "np_hake")) isTRUE(np_hake) else isTRUE(conditions[[gate]])
    if (!on) msg <- NULL
  }
  if (!is.null(msg)) message(msg)
  row$default
}

#' Upgrade deprecated fleet_control column names to canonical, in place.
#'
#' The single migration point for legacy fleet_control column names: every
#' canonical column carries its historical spellings in the schema `aliases`
#' field, and this walks them, renaming any present old name to the canonical
#' one. Both `read_data()` (on the xlsx path) and `switch_check()` (on every
#' fit path) call it, so a data list built either way is upgraded identically
#' from the one schema -- the hand-coded rename cascades that used to live in
#' both are gone.
#'
#' Double-fire-safe: a no-op when the old name is absent (so re-running on an
#' already-upgraded list is silent), and it never clobbers an existing
#' canonical column. Emits one deprecation message per rename actually applied.
#'
#' @param fc A `fleet_control` data frame (or NULL).
#' @return `fc` with any deprecated column names upgraded to canonical.
#' @keywords internal
#' @noRd
.rce_upgrade_fleet_control_aliases <- function(fc) {
  if (is.null(fc)) return(fc)
  schema <- .rce_column_schema()
  for (row in schema) {
    if (row$sheet != "fleet_control" || length(row$aliases) == 0L) next
    for (old in row$aliases) {
      if (!is.null(fc[[old]])) {
        if (is.null(fc[[row$name]])) fc[[row$name]] <- fc[[old]]
        fc[[old]] <- NULL
        message(sprintf("'%s' is deprecated; use '%s'.", old, row$name))
      }
    }
  }
  fc
}

#' Upgrade deprecated data_list-level (control / bioenergetics) names to canonical.
#'
#' The analogue of `.rce_upgrade_fleet_control_aliases()` for the top-level
#' data_list elements that are NOT fleet_control columns -- the control scalars
#' and bioenergetics per-species vectors, whose deprecated names live in the
#' same schema `aliases` field (e.g. `sigma_rec_prior` -> `sigma_rec`,
#' `Diet_loglike` -> `Diet_distribution`). Double-fire-safe; one message per
#' rename applied.
#'
#' @param data_list An Rceattle data list (or NULL).
#' @return `data_list` with any deprecated control/bioenergetics element names
#'   upgraded to canonical.
#' @keywords internal
#' @noRd
.rce_upgrade_data_list_aliases <- function(data_list) {
  if (is.null(data_list)) return(data_list)
  schema <- .rce_column_schema()
  for (row in schema) {
    if (row$sheet == "fleet_control" || length(row$aliases) == 0L) next
    for (old in row$aliases) {
      if (!is.null(data_list[[old]])) {
        if (is.null(data_list[[row$name]])) data_list[[row$name]] <- data_list[[old]]
        data_list[[old]] <- NULL
        message(sprintf("'%s' is deprecated; use '%s'.", old, row$name))
      }
    }
  }
  data_list
}

#' Rows for one sheet, in schema (write) order.
#' @keywords internal
#' @noRd
.rce_schema_rows <- function(sheet, include_orphans = FALSE) {
  rows <- .rce_column_schema()
  rows <- Filter(function(r) r$sheet == sheet, rows)
  if (!include_orphans) rows <- Filter(function(r) r$status != "orphan", rows)
  rows
}

#' Canonical column/scalar names for one sheet, in write order.
#' @keywords internal
#' @noRd
.rce_schema_names <- function(sheet, include_orphans = FALSE) {
  unname(vapply(.rce_schema_rows(sheet, include_orphans),
                function(r) r$name, character(1)))
}

